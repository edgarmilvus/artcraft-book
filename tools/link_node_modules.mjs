/**
 * Point every chapter project at the repository's single `node_modules`.
 *
 * The book's twenty chapters ship ninety-odd small projects. Each one
 * declares its own `package.json`, and each one used to carry its own
 * copy of the dependency tree — a gigabyte of duplicates that made the
 * repository impossible to clone and impossible to diff.
 *
 * Node resolves `require` and `import` by walking *up* the directory
 * tree, so a project at `chapter7/exercise_2/…/files/` finds the root
 * `node_modules` without a symlink at all. The symlinks below are not
 * needed for resolution — they exist for the tools that do not walk up:
 * `npm run`, which reads the *nearest* `node_modules/.bin`, and the
 * `.bin` shims a listing's own `package.json` scripts expect.
 *
 * Run it directly, or let `npm install` run it as `postinstall`:
 *
 *     node tools/link_node_modules.mjs
 *     node tools/link_node_modules.mjs --check   # report only
 *     node tools/link_node_modules.mjs --unlink  # remove the symlinks
 */
import { existsSync, lstatSync, readdirSync, readlinkSync, rmSync, symlinkSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const TARGET = join(ROOT, "node_modules");

/** Every directory under the chapter directories that holds a `package.json`. */
function projectDirs() {
  const found = [];
  for (const entry of readdirSync(ROOT, { withFileTypes: true })) {
    if (!entry.isDirectory() || !/^chapter\d+$/.test(entry.name)) continue;
    const chapter = join(ROOT, entry.name);
    for (const section of readdirSync(chapter, { withFileTypes: true })) {
      if (!section.isDirectory()) continue;
      const sectionDir = join(chapter, section.name);
      for (const kind of readdirSync(sectionDir, { withFileTypes: true })) {
        if (!kind.isDirectory()) continue;
        const dir = join(sectionDir, kind.name, "files");
        if (existsSync(join(dir, "package.json"))) found.push(dir);
      }
    }
  }
  return found.sort();
}

const mode = process.argv[2] ?? "--link";
if (!existsSync(TARGET)) {
  console.error(`no root node_modules at ${TARGET} — run "npm install" first`);
  process.exit(1);
}

const dirs = projectDirs();
let linked = 0;
let already = 0;
let repaired = 0;
let missing = 0;

for (const dir of dirs) {
  const link = join(dir, "node_modules");
  const stat = lstatSync(link, { throwIfNoEntry: false });
  if (stat?.isSymbolicLink()) {
    const current = resolve(dirname(link), readlinkSync(link));
    if (current === TARGET) {
      already += 1;
      continue;
    }
    rmSync(link, { recursive: true, force: true });
    repaired += 1;
  } else if (stat?.isDirectory()) {
    // A real directory: a stale copy of the dependency tree.
    rmSync(link, { recursive: true, force: true });
    repaired += 1;
  } else if (stat) {
    rmSync(link, { force: true });
    repaired += 1;
  } else {
    missing += 1;
  }

  if (mode === "--check") continue;
  symlinkSync(relative(dir, TARGET), link, "dir");
  linked += 1;
}

if (mode === "--unlink") {
  console.log(`unlinked ${repaired} project node_modules`);
  process.exit(0);
}

if (mode === "--check") {
  console.log(
    `${dirs.length} projects: ${already} linked, ${missing} missing, ${repaired} stale`,
  );
  if (missing || repaired) {
    console.log('run "npm run link" to apply');
    process.exit(1);
  }
  process.exit(0);
}

console.log(
  `${dirs.length} projects: ${linked} linked, ${already} already correct, ${repaired} repaired`,
);
