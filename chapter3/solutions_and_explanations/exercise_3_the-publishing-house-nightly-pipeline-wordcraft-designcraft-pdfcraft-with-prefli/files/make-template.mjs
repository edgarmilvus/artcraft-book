import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
const [cwd] = process.argv.slice(2);
const t = new StdioClientTransport({ command: "designcraft-cli", args: ["mcp"], cwd });
const c = new Client({ name: "tpl", version: "1" }, { capabilities: {} });
await c.connect(t);
const txt = (r) => { const b = r.content.find(x=>x.type==="text"); try { return JSON.parse(b.text); } catch { return b.text; } };
const call = async (n,a={}) => txt(await c.callTool({ name:n, arguments:a }));
console.log("new:", JSON.stringify(await call("new_document", { width: 612, height: 792, pages: 1, margins: 72, title: "House master" })));
console.log("frame:", JSON.stringify(await call("execute", { command: "frame.create", params: { rect: [72,72,540,720], content: "text", text: "" } })));
console.log("save:", JSON.stringify(await call("save_document", { path: "templates/house-master.designcraft" })));
await c.close();
