import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
import { mkdirSync } from "node:fs";
const root = process.argv[2]; mkdirSync(root,{recursive:true});
const t = new StdioClientTransport({command:"wordcraft-cli",args:["mcp"],cwd:root,stderr:"pipe"}); t.stderr?.on("data",()=>{});
const c = new Client({name:"probe",version:"1"},{capabilities:{}}); await c.connect(t);
const unwrap=(r)=>{const b=r.content?.find(x=>x.type==="text"); try{return JSON.parse(b.text)}catch{return b.text}};
const call=async(n,a={})=>{const r=await c.callTool({name:n,arguments:a}); return unwrap(r)};
const ex=async(cmd,params={})=>call('execute',{command:cmd,params});
await call('new_document',{width:612,height:792});
await ex('text.insert',{text:'Keep. '});
await ex('review.trackChanges',{});
await ex('file.setAuthor',{name:'Editor'});
await ex('text.insert',{text:'FIRST.'});
await ex('text.insert',{text:' Keep. '});
await ex('file.setAuthor',{name:'Author'});
await ex('text.insert',{text:'SECOND.'});
console.log('changes',JSON.stringify(await ex('review.changes',{}),null,1));
console.log('reject id1'); await ex('review.reject',{id:1});
console.log('after',JSON.stringify(await ex('review.changes',{}),null,1));
console.log('doc',JSON.stringify(await call('inspect_document',{})));
await c.close();
