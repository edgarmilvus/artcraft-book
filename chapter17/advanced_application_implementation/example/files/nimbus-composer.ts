/* ============================================================================
 * NimbusContracts — Headless Office Pipeline
 * ----------------------------------------------------------------------------
 * nimbus-composer.ts — the WordCraft half: template → merged DOCX → PDF.
 *
 * Owns the "business logic" of turning a template + merge data into a filled
 * DOCX. It is deliberately stateless with respect to the bridge so the same
 * instance can be reused across many requests in a worker.
 * ========================================================================== */

import type {
  GenerateDocumentRequest,
  OfficeMcpBridge,
} from "./office-bridge.js";

export interface ComposeContext {
  /** Absolute path to the tenant's template DOCX (already validated). */
  templatePath: string;
  /** Where the merged DOCX should be written. */
  outputDocxPath: string;
  /** Where the exported PDF should be written. */
  outputPdfPath: string;
  /** The validated request body. */
  request: GenerateDocumentRequest;
  /** The resolved, sanitized merge map (already applied to placeholders). */
  mergeMap: Record<string, string>;
}

export class WordCraftComposer {
  constructor(private readonly bridge: OfficeMcpBridge) {}

  /**
   * Compose the merged DOCX and export it to PDF.
   *
   * The sequence is significant:
   *   1.  Open the tenant's template. Every save below names an explicit
   *       output path, so the master template on disk is never rewritten.
   *   2.  Replace all `{{ key }}` placeholders with sanitized values.
   *   3.  Update visible metadata (title, author, subject).
   *   4.  Insert any conditional blocks (e.g. "Payment Terms" table).
   *   5.  Insert the table of contents *last* so heading pages resolve.
   *   6.  Save the DOCX in place.
   *   7.  Export the PDF.
   */
  async compose(ctx: ComposeContext): Promise<void> {
    const { templatePath, outputDocxPath, outputPdfPath, mergeMap, request } = ctx;

    // ---- 1. Open the template. -------------------------------------------
    await this.bridge.wcExecute("file.open", { path: templatePath });

    // ---- 2. Substitute placeholders. Each replaceAll is its own undo step,
    //         batched for efficiency but with `keepGoing: false` so we abort
    //         if any single substitution fails — a partially merged MSA is
    //         worse than none.
    const substitutions = Object.entries(mergeMap).map(([key, value]) => ({
      command: "edit.replaceAll",
      params: {
        text: `{{${key}}}`,
        with: value,
        matchCase: true,
        wholeWord: false,
        regex: false,
      },
    }));

    if (substitutions.length > 0) {
      await this.bridge.wcBatch(substitutions, /* keepGoing */ false);
    }

    // ---- 3. Metadata.
    await this.bridge.wcExecute("file.properties", {
      title: mergeMap["document_title"] ?? `${request.templateId} — ${mergeMap["vendor_name"] ?? "Untitled"}`,
      author: request.documentAuthor,
      subject: `Classification: ${request.classification}`,
      keywords: [
        `tenant:${request.tenantId}`,
        `classification:${request.classification}`,
        `template:${request.templateId}`,
      ].join("; "),
      category: request.templateId,
      comments: `Generated by NimbusContracts pipeline ${request.idempotencyKey}`,
    });

    // ---- 4. Conditional blocks.
    // Payment schedule block only materializes when the payload carries rows.
    const paymentRows = this.parsePaymentRows(mergeMap["payment_schedule_csv"]);
    if (paymentRows.length > 0) {
      await this.bridge.wcBatch([
        // A heading so the block is TOC-visible. The style is applied
        // *before* the text, so the paragraph is already a Heading 1 when
        // the table of contents is generated.
        { command: "text.newParagraph", params: {} },
        { command: "para.style", params: { style: "Heading 1" } },
        { command: "text.insert", params: { text: "Payment Schedule" } },
        { command: "text.newParagraph", params: {} },
        // Build the table: one header row plus one row per milestone.
        {
          command: "insert.table",
          params: {
            rows: paymentRows.length + 1,
            cols: 3,
            style: "GridTable1Light",
          },
        },
      ], /* keepGoing */ false);

      // Fill the table cell by cell. `insert.table` leaves the caret in the
      // first cell and `text.tab` moves to the next one, wrapping to the
      // next row at the end of a row — so the walk is a flat sequence of
      // "insert, tab" pairs with no tab after the very last cell.
      const rows: string[][] = [
        ["Milestone", "Due Date", "Amount"],
        ...paymentRows.map((row) => [row.milestone, row.dueDate, row.amount]),
      ];
      for (const [r, cells] of rows.entries()) {
        for (const [c, cell] of cells.entries()) {
          await this.bridge.wcExecute("text.insert", { text: cell });
          const isLastCellOfLastRow = r === rows.length - 1 && c === cells.length - 1;
          if (!isLastCellOfLastRow) {
            await this.bridge.wcExecute("text.tab", {});
          }
        }
      }
      // Leave the table. `text.newParagraph` inside the last cell would
      // open a *new paragraph inside the cell*, so the caret is moved out
      // of the table first — `caret.docEnd` lands on the empty paragraph
      // the body always keeps after a trailing table.
      await this.bridge.wcExecute("caret.docEnd", {});
      await this.bridge.wcExecute("text.newParagraph", {});
    }

    // ---- 5. Table of contents (after all headings are inserted).
    await this.bridge.wcExecute("references.toc", {
      levels: 3,
      title: "Contents",
    });

    // ---- 6. Save DOCX (native .docx; the extension selects the writer).
    await this.bridge.wcExecute("file.save", { path: outputDocxPath });

    // ---- 7. Export PDF. WordCraft's exporter honours pagination, headers,
    //         and every style the composer applied.
    await this.bridge.wcExecute("file.exportPdf", { path: outputPdfPath });
  }

  /**
   * Parse the `payment_schedule_csv` merge field into structured rows.
   * The CSV format is `milestone,due_date,amount` per line; blank lines
   * are ignored so tenants can hand-edit the cell without breaking.
   */
  private parsePaymentRows(raw: string | undefined): Array<{
    milestone: string; dueDate: string; amount: string;
  }> {
    if (!raw) return [];
    return raw
      .split(/\r?\n/)
      .map((l) => l.trim())
      .filter((l) => l.length > 0)
      .map((line) => {
        const [milestone = "", dueDate = "", amount = ""] = line.split(",");
        return {
          milestone: milestone.trim(),
          dueDate: dueDate.trim(),
          amount: amount.trim(),
        };
      });
  }
}
